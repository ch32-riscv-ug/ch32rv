/// One CSV line's fields, honouring double-quoted fields (`""` is a quote).
fn split_quoted(line: &str) -> Vec<String> {
    let mut fields = Vec::new();
    let mut cur = String::new();
    let mut in_quotes = false;
    let mut chars = line.chars().peekable();
    while let Some(ch) = chars.next() {
        match ch {
            '"' if in_quotes && chars.peek() == Some(&'"') => {
                cur.push('"');
                chars.next();
            }
            '"' => in_quotes = !in_quotes,
            ',' if !in_quotes => fields.push(std::mem::take(&mut cur)),
            _ => cur.push(ch),
        }
    }
    fields.push(cur);
    fields
}

/// One named field of the option USER byte, for a family: one bit, or a range (`RST_MODE[4:3]`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OptionUserField {
    /// The lowest bit of the field within the USER byte.
    pub bit: u8,
    /// How many bits it takes (1 for a single bit).
    pub width: u8,
    /// Field name from the reference manual (e.g. `IWDGSW`, `STOPRST`, `RST_MODE`).
    pub field: String,
    /// Its default value (the reference manual's; fields the manual leaves open are not listed).
    pub default: u8,
}

impl OptionUserField {
    /// The field's bits within the USER byte.
    pub fn mask(&self) -> u8 {
        (((1u16 << self.width) - 1) << self.bit) as u8
    }

    /// The field's value in `user`.
    pub fn get(&self, user: u8) -> u8 {
        (user & self.mask()) >> self.bit
    }

    /// `user` with this field set to `value` (masked to its width).
    pub fn set(&self, user: u8, value: u8) -> u8 {
        (user & !self.mask()) | ((value << self.bit) & self.mask())
    }
}

/// en: The named USER-byte option fields for a DB `family` string (e.g. `CH32L103`, `CH32V20x`,
/// `CH32V307`), sorted high bit first. Empty when the family is not in the DB.
/// ja: DB の family 文字列に対する USER byte の名前付き field 群(高 bit 順)。DB に無ければ空。
pub fn option_user_fields(family: &str) -> Vec<OptionUserField> {
    let mut out: Vec<OptionUserField> = GENERATED_OPTION_FIELDS
        .lines()
        .filter_map(|line| {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                return None;
            }
            // family,bit,width,field,default,option,evt_argument,evt_values,words
            let f: Vec<&str> = line.split(',').collect();
            let [fam, bit, width, field, default, ..] = f.as_slice() else {
                return None;
            };
            if !fam.eq_ignore_ascii_case(family) {
                return None;
            }
            let width: u8 = width.parse().ok()?;
            let bit: u8 = bit.parse().ok()?;
            if width == 0 || bit + width > 8 {
                return None;
            }
            // A field the manual leaves open is listed only for its EVT name (option_semantics).
            let default: u8 = default.parse().ok()?;
            Some(OptionUserField {
                bit,
                width,
                field: (*field).to_owned(),
                default,
            })
        })
        .collect();
    out.sort_by_key(|f| core::cmp::Reverse(f.bit));
    out
}

/// en: One value of an [`OptionSemantic`]: the word written on the command line, the field value
/// it stands for, and the WCH EVT constant it is (`FLASH_UserOptionByteConfig` argument).
/// ja: 意味名の値 1 つ: コマンドで書く語、field の値、それに当たる EVT の定数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct OptionValue {
    pub word: &'static str,
    pub bits: u8,
    pub evt: &'static str,
}

/// en: A USER-byte option under its semantic name - one argument of the WCH EVT
/// `FLASH_UserOptionByteConfig` (OB_IWDG, OB_STOP, OB_RST, ...), from the device DB's
/// `option_byte_fields` (`option`, `evt_argument`, `evt_values`; the value words are derived from
/// the EVT constants by `cargo xtask db-gen`, docs/cli.ja.md §4.3). The polarity lives in the value
/// words (`stop-reset=on` is `OB_STOP_RST`, bit 0), never in the caller.
/// ja: USER byte の option を意味名で表したもの。DB の `option_byte_fields` の EVT の列から作る
/// (値の語は db-gen が EVT の定数から作る)。極性は値の語が持つ(`stop-reset=on` は `OB_STOP_RST`、bit 0)。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OptionSemantic {
    /// The key on the command line (`iwdg`, `stop-reset`, `reset-pin`, `start-mode`, ...).
    pub key: &'static str,
    /// The reference-manual field it is (`IWDGSW`, `RST_MODE`, ...).
    pub field: &'static str,
    /// The `FLASH_UserOptionByteConfig` argument (`OB_IWDG`, `OB_RST`, ...).
    pub evt_argument: &'static str,
    /// The lowest bit within the USER byte.
    pub bit: u8,
    /// How many bits it takes.
    pub width: u8,
    pub values: Vec<OptionValue>,
}

impl OptionSemantic {
    /// The field's bits within the USER byte.
    pub fn mask(&self) -> u8 {
        (((1u16 << self.width) - 1) << self.bit) as u8
    }

    /// The field's value in `user`.
    pub fn get(&self, user: u8) -> u8 {
        (user & self.mask()) >> self.bit
    }

    /// `user` with this field set to `bits`.
    pub fn set(&self, user: u8, bits: u8) -> u8 {
        (user & !self.mask()) | ((bits << self.bit) & self.mask())
    }

    /// The value word for a field value (`None` for a value EVT gives no name).
    pub fn word(&self, bits: u8) -> Option<&OptionValue> {
        self.values.iter().find(|v| v.bits == bits)
    }
}

/// Every family of the generated option field table with its semantic options (bit order).
fn semantic_table() -> &'static [(&'static str, Vec<OptionSemantic>)] {
    static TABLE: std::sync::OnceLock<Vec<(&'static str, Vec<OptionSemantic>)>> =
        std::sync::OnceLock::new();
    TABLE.get_or_init(|| {
        let mut out: Vec<(&'static str, Vec<OptionSemantic>)> = Vec::new();
        for line in GENERATED_OPTION_FIELDS.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let f: Vec<&'static str> = line.split(',').collect();
            let [fam, bit, width, field, _default, key, arg, evt, words] = f.as_slice() else {
                continue;
            };
            let i = match out.iter().position(|(x, _)| x == fam) {
                Some(i) => i,
                None => {
                    out.push((fam, Vec::new()));
                    out.len() - 1
                }
            };
            let (Ok(bit), Ok(width)) = (bit.parse::<u8>(), width.parse::<u8>()) else {
                continue;
            };
            if key.is_empty() || width == 0 || bit + width > 8 {
                continue;
            }
            // `<field value>=<constant>` and `<field value>=<word>`, joined on the field value.
            let pairs = |s: &'static str| {
                s.split(';')
                    .filter_map(|p| p.split_once('='))
                    .filter_map(|(v, x)| Some((v.parse::<u8>().ok()?, x)))
                    .collect::<Vec<_>>()
            };
            let consts = pairs(evt);
            let values = pairs(words)
                .into_iter()
                .filter_map(|(bits, word)| {
                    let evt = consts.iter().find(|(b, _)| *b == bits)?.1;
                    Some(OptionValue { word, bits, evt })
                })
                .collect();
            out[i].1.push(OptionSemantic {
                key,
                field,
                evt_argument: arg,
                bit,
                width,
                values,
            });
        }
        for (_, s) in &mut out {
            s.sort_by_key(|o| o.bit);
        }
        out
    })
}

/// en: The semantic USER-byte options of a DB family: the `FLASH_UserOptionByteConfig` arguments
/// of its WCH EVT, as the device DB's `option_byte_fields` gives them (`option` column). A USER
/// field with no `option` (CH32V103 PORCTR) is reached by its reference-manual field name as
/// `user.<field>`. `None` when the family is not in the DB.
/// ja: DB family の意味名の option(DB の `option_byte_fields` の `option` 列)。`option` の無い
/// field は RM の field 名で `user.<field>` と書く。DB に無い family は `None`。
pub fn option_semantics(family: &str) -> Option<&'static [OptionSemantic]> {
    semantic_table()
        .iter()
        .find(|(f, _)| f.eq_ignore_ascii_case(family))
        .map(|(_, s)| s.as_slice())
}

/// en: Every semantic option key some family has (to tell "this family lacks it" from "unknown").
/// ja: いずれかの family が持つ意味名の key 全部。
pub fn option_semantic_keys() -> Vec<&'static str> {
    let mut k: Vec<&'static str> = semantic_table()
        .iter()
        .flat_map(|(_, s)| s.iter().map(|o| o.key))
        .collect();
    k.sort_unstable();
    k.dedup();
    k
}

/// Silicon-revision bits `[7:4]` of the device_id are don't-care when matching (every delivered row
/// uses this mask; `xtask db-gen` rejects any other).
const DEVICE_ID_MASK: u32 = 0xFFFF_FF0F;

/// en: How a chip_id resolved against the DB. ja: chip_id を DB で解決した結果。
#[derive(Debug, Clone, PartialEq)]
pub enum Resolution<'a> {
    /// Exactly one SKU matched.
    Sku(&'a SkuRecord),
    /// Several SKUs matched but all share a family (SKU ambiguous, family known).
    Family(String, Vec<&'a SkuRecord>),
    /// No SKU matched (unknown / gap-series part).
    Unknown,
}

impl Db {
    /// en: The device id read from memory, for a probe whose attach gave none (a CH32V103 over
    /// an OEP probe: its debug module has no WCH id register). Each address some part keeps its id
    /// at is read in turn, and a value is taken only when it names a part that keeps it there.
    /// ja: attach が ID を返さない probe 向けに、メモリから ID を読む。型番が ID を置く番地を順に
    /// 読み、その番地に ID を置く型番を名指す値だけを採る。
    pub fn chip_id_from_memory(&self, mut read: impl FnMut(u32) -> Option<u32>) -> Option<u32> {
        let mut addrs: Vec<u32> = self.skus.iter().filter_map(|s| s.id_addr).collect();
        addrs.sort_unstable();
        addrs.dedup();
        addrs.into_iter().find_map(|at| {
            let id = read(at)?;
            self.skus
                .iter()
                .any(|s| {
                    s.id_addr == Some(at)
                        && s.device_id.map(|d| d & DEVICE_ID_MASK) == Some(id & DEVICE_ID_MASK)
                })
                .then_some(id)
        })
    }
}

impl Resolution<'_> {
    /// en: Flash and SRAM bytes of the matched part: one SKU's, or those every candidate sharing
    /// the id has (a temperature grade, CH32V006K8U6/U7). None when unknown or when they differ.
    /// ja: 一致した型番の flash と SRAM のバイト数。ID を共有する候補が皆同じならその値。
    pub fn geometry(&self) -> Option<(u32, u32)> {
        match self {
            Resolution::Sku(s) => Some((s.flash_bytes, s.sram_bytes)),
            Resolution::Family(_, c) => {
                let first = c.first()?;
                c.iter()
                    .all(|s| s.flash_bytes == first.flash_bytes && s.sram_bytes == first.sram_bytes)
                    .then_some((first.flash_bytes, first.sram_bytes))
            }
            Resolution::Unknown => None,
        }
    }
}

/// en: Parse one `sku,family,series,device_id,id_addr,flash_bytes,sram_bytes,verified[,...]`
/// table. Trailing columns are ignored, so the provisional overlay can carry its request number
/// without a second parser. Malformed rows are skipped rather than failing the whole table.
/// ja: SKU 表を 1 つ読む。9 列目以降(overlay の依頼番号)は無視。壊れた行は飛ばす。
fn parse_sku_table(csv: &str, provisional: bool) -> Vec<SkuRecord> {
    let mut out = Vec::new();
    for line in csv.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            continue;
        }
        let f: Vec<&str> = line.split(',').collect();
        let (
            Some(sku),
            Some(family),
            Some(series),
            Some(device_id),
            Some(flash),
            Some(sram),
            Some(verified),
        ) = (
            f.first(),
            f.get(1),
            f.get(2),
            f.get(3),
            f.get(5),
            f.get(6),
            f.get(7),
        )
        else {
            continue;
        };
        let hex = |v: &str| {
            v.strip_prefix("0x")
                .and_then(|h| u32::from_str_radix(h, 16).ok())
        };
        let device_id = hex(device_id);
        out.push(SkuRecord {
            sku: (*sku).to_owned(),
            family: (*family).to_owned(),
            series: (*series).to_owned(),
            device_id,
            id_addr: f.get(4).and_then(|a| hex(a)),
            flash_bytes: flash.parse().unwrap_or(0),
            sram_bytes: sram.parse().unwrap_or(0),
            // `verified` = the device_id was confirmed on real silicon by this project; the rest
            // is datasheet/reference data.
            verified: *verified == "true",
            provisional,
        });
    }
    out
}

/// en: The device DB: a read-only view over the generated data plus overlays.
/// ja: device DB。生成物 + overlay をまとめた読み取り専用ビュー。
#[derive(Debug, Default)]
pub struct Db {
    skus: Vec<SkuRecord>,
}

impl Db {
    /// en: Built-in (generated) DB, embedded at compile time from `generated/skus.csv`.
    /// ja: 内蔵(生成済み)DB。`generated/skus.csv` をコンパイル時に埋め込む。
    pub fn builtin() -> Self {
        let mut skus = parse_sku_table(GENERATED_SKUS, false);
        // The overlay only fills gaps: once db-gen starts delivering a SKU (by name or by masked
        // device_id) the generated row wins and the stale provisional one is dropped, so a
        // forgotten overlay entry can never shadow real data.
        for row in parse_sku_table(PROVISIONAL_SKUS, true) {
            let shadowed = skus.iter().any(|g| {
                g.sku == row.sku
                    || match (g.device_id, row.device_id) {
                        (Some(a), Some(b)) => a & DEVICE_ID_MASK == b & DEVICE_ID_MASK,
                        _ => false,
                    }
            });
            if !shadowed {
                skus.push(row);
            }
        }
        Self { skus }
    }

    /// en: The built-in DB plus a user-supplied overlay CSV (`--db` / `CH32RV_DB`), for driving a
    /// part the shipped tables do not carry yet. Same columns as `generated/skus.csv`
    /// (`sku,family,series,device_id,id_addr,flash_bytes,sram_bytes,verified`, trailing columns
    /// ignored, `#` comments allowed). Overlay rows are flagged [`SkuRecord::provisional`] so the
    /// output never passes them off as shipped data, and - unlike the in-tree
    /// `provisional/skus.csv`, which only fills gaps - **an overlay row wins** over a generated one
    /// with the same SKU name or the same revision-masked device_id: the whole point of passing the
    /// file is to override what the build knows.
    /// ja: 内蔵 DB + 利用者指定の overlay CSV(`--db` / `CH32RV_DB`)。未収載の部品を動かすための逃げ道。
    /// 列は `generated/skus.csv` と同じ(9 列目以降は無視、`#` はコメント)。overlay 行は
    /// [`SkuRecord::provisional`] が立つ。**同名 SKU / 同一マスク device_id では overlay が勝つ**
    /// (穴埋め専用の in-tree `provisional/skus.csv` とはここが違う。上書きこそが指定の目的)。
    pub fn with_overlay(path: &std::path::Path) -> Result<Self, String> {
        let csv = std::fs::read_to_string(path)
            .map_err(|e| format!("could not read the DB overlay {}: {e}", path.display()))?;
        let rows = parse_sku_table(&csv, true);
        if rows.is_empty() {
            return Err(format!(
                "the DB overlay {} has no usable rows (expected `sku,family,series,device_id,id_addr,flash_bytes,sram_bytes,verified`)",
                path.display()
            ));
        }
        let mut skus = Self::builtin().skus;
        for row in rows {
            skus.retain(|g| {
                g.sku != row.sku
                    && match (g.device_id, row.device_id) {
                        (Some(a), Some(b)) => a & DEVICE_ID_MASK != b & DEVICE_ID_MASK,
                        _ => true,
                    }
            });
            skus.push(row);
        }
        Ok(Self { skus })
    }

    pub fn skus(&self) -> &[SkuRecord] {
        &self.skus
    }

    /// en: The distinct DB families a `--chip` name means: a SKU, a family or a series, matched
    /// exactly (case aside; docs/freeze-decisions.ja.md §1 - no prefix matching, so `--chip C` is
    /// not every part). Empty when the name is not in the DB (e.g. a gap-series part).
    /// ja: `--chip` 名(SKU / family / series、大小を除く完全一致。前方一致はしない)が指す DB family 群。
    /// DB に無ければ空。
    pub fn families_for_chip_name(&self, name: &str) -> Vec<String> {
        let mut fams: Vec<String> = self
            .skus
            .iter()
            .filter(|s| {
                s.sku.eq_ignore_ascii_case(name)
                    || s.family.eq_ignore_ascii_case(name)
                    || s.series.eq_ignore_ascii_case(name)
            })
            .map(|s| s.family.clone())
            .collect();
        fams.sort();
        fams.dedup();
        fams
    }

    /// en: Whether the chip a `--chip` name means can have a USB port: `Some(true)` when any of
    /// its parts has one, `Some(false)` when the DB says none does, `None` when the name is not in
    /// the DB or the DB says nothing about its parts' USB. ja: `--chip` の chip に USB がありうるか。
    pub fn chip_has_usb(&self, name: &str) -> Option<bool> {
        let mut known = false;
        for s in self.skus.iter().filter(|s| {
            s.sku.eq_ignore_ascii_case(name)
                || s.family.eq_ignore_ascii_case(name)
                || s.series.eq_ignore_ascii_case(name)
        }) {
            match part_has_usb(&s.sku) {
                Some(true) => return Some(true),
                Some(false) => known = true,
                None => {}
            }
        }
        known.then_some(false)
    }

    /// en: When `name` is a SKU with a known device id and the chip read (`chip_id`) is another
    /// part, the SKU the chip resolves to (or its id); `None` when they agree or when `name` is a
    /// family / series, or a SKU the DB has no device id for (then only the family is checked).
    /// ja: `name` が device id の分かる SKU で、読んだ chip が別の part なら、その chip の SKU(か id)。
    /// 一致、または family / series、device id の無い SKU なら `None`(family だけで照合する)。
    pub fn sku_conflict(&self, name: &str, chip_id: u32) -> Option<String> {
        let want = self
            .skus
            .iter()
            .find(|s| s.sku.eq_ignore_ascii_case(name))?
            .device_id?;
        if want & DEVICE_ID_MASK == chip_id & DEVICE_ID_MASK {
            return None;
        }
        Some(match self.resolve_by_chip_id(chip_id) {
            Resolution::Sku(s) => s.sku.clone(),
            _ => format!("chip id 0x{chip_id:08x}"),
        })
    }

    /// en: [`Self::resolve_by_chip_id`], then narrowed by the part the user named: when the ID
    /// leaves several candidates (parts that share one ID, data request 0011) and `--chip` names
    /// one of them, that part is the answer. A family or series name narrows nothing.
    /// ja: `resolve_by_chip_id` の結果を、利用者が名指した型番で絞る。ID が複数の候補を残し
    /// (1 つの ID を共有する型番、依頼 0011)、`--chip` がその 1 つなら、それを答えにする。
    /// family / series の名前では絞らない。
    pub fn resolve_with_chip(&self, chip_id: u32, chip: Option<&str>) -> Resolution<'_> {
        match (self.resolve_by_chip_id(chip_id), chip) {
            (Resolution::Family(fam, cands), Some(name)) => {
                match cands.iter().find(|s| s.sku.eq_ignore_ascii_case(name)) {
                    Some(one) => Resolution::Sku(one),
                    None => Resolution::Family(fam, cands),
                }
            }
            (r, _) => r,
        }
    }

    /// en: Resolve a live `chip_id` (AttachChip response) to a SKU. Silicon-revision bits `[7:4]` are
    /// masked out. Fail-closed: an ambiguous multi-family match returns `Unknown` rather than a
    /// guess; a same-family ambiguity returns `Family` with the candidates.
    /// ja: 実機の `chip_id` を SKU へ解決。rev `[7:4]` は無視。多 family で曖昧なら推測せず `Unknown`、
    /// 同 family の曖昧は候補付き `Family` を返す(fail-closed)。
    pub fn resolve_by_chip_id(&self, chip_id: u32) -> Resolution<'_> {
        let masked = chip_id & DEVICE_ID_MASK;
        let hits: Vec<&SkuRecord> = self
            .skus
            .iter()
            .filter(|s| s.device_id.map(|d| d & DEVICE_ID_MASK) == Some(masked))
            .collect();
        match hits.as_slice() {
            [] => Resolution::Unknown,
            [one] => Resolution::Sku(one),
            many => {
                let fam = &many[0].family;
                if many.iter().all(|s| &s.family == fam) {
                    Resolution::Family(fam.clone(), hits)
                } else {
                    Resolution::Unknown
                }
            }
        }
    }
}

/// One SKU record. Column meanings: docs/architecture.ja.md §3.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct SkuRecord {
    pub sku: String,
    pub family: String,
    /// Part-number series (keys debug wiring); may be narrower than `family`.
    pub series: String,
    /// device_id read from memory (from measured evidence).
    pub device_id: Option<u32>,
    /// en: Where the part keeps its device_id in memory (`id_addr`).
    /// ja: device_id を置く番地。
    #[serde(default)]
    pub id_addr: Option<u32>,
    pub flash_bytes: u32,
    pub sram_bytes: u32,
    /// en: Verified on real silicon (kept distinct from merely "implemented").
    /// ja: 実機確認済みか(「実装済み」と区別する)。
    pub verified: bool,
    /// en: Comes from the provisional overlay (request to ch32-device-data pending).
    /// ja: 暫定 overlay 由来か(ch32-device-data へ依頼中)。
    pub provisional: bool,
}

