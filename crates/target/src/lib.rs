//! en: Target device DB. Never hand-written: the DB is generated from `ch32-device-data`
//! (geometry / memory map / option splits / DM addresses, and device_id from WCH's EVT ChipID
//! lists and measurements), and committed under `generated/` (docs/architecture.ja.md §3). A part
//! with no single known device_id is still listed, without one: `--chip` knows the name and checks
//! its family, but a chip id never resolves to it. Missing data is requested from
//! ch32-device-data (docs/data-requests/); until delivery, a provisional overlay under
//! `provisional/` fills the gap. Every SKU carries `verified` / `provisional` flags that
//! surface in tool output.
//! The built-in DB is generated by `cargo xtask db-gen` into `generated/skus.csv` and embedded
//! with `include_str!`, so the build never reads a neighbour repo.
//!
//! ja: target device DB。手書きせず、ch32-device-data(device_id は WCH EVT の ChipID 一覧と実測)
//! からの生成物を `generated/` に commit する。device_id が 1 つに決まらない型番も ID 無しで載せる
//! (`--chip` は名前を知り family を照合するが、chip id からその型番へは引かない)。不足データは ch32-device-data へ依頼し、納品までは
//! `provisional/` の暫定 overlay で進む。SKU ごとに verified / provisional flag を持ち出力に出す。
//! 内蔵 DB は `cargo xtask db-gen` が `generated/skus.csv` を生成し `include_str!` で埋め込む。
//!
//! ```
//! use ch32rv_target::{Db, Resolution};
//!
//! let db = Db::builtin();
//! // Resolve a live chip id to a SKU. The silicon-revision nibble (chip_id bits `[7:4]`) is masked,
//! // and resolution is fail-closed: a cross-family-ambiguous id yields `Family`, an unknown one `Unknown`.
//! match db.resolve_by_chip_id(0x3070_0528) {
//!     Resolution::Sku(s) => println!("{}: {} bytes flash", s.sku, s.flash_bytes),
//!     Resolution::Family(fam, cands) => println!("{fam} ({} candidates)", cands.len()),
//!     Resolution::Unknown => println!("not in the DB"),
//! }
//! ```

