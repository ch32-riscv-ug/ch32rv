/// en: Provenance of the embedded device DB, for `version --json` reproducibility
/// (docs/architecture.ja.md §3). ja: 埋め込み device DB の来歴。`version --json` の再現性表示用。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DbProvenance {
    /// The `ch32-device-data` revision the DB was generated from (from the generated headers).
    /// None if the generated files carry no `# source:` header.
    pub source_rev: Option<String>,
    /// A stable identity fingerprint of the embedded DB bytes (`fnv1a64:<hex>`), in the same
    /// convention as `flash_stub_digest`. Not cryptographic - it just pins what is baked in.
    pub digest: String,
}

/// en: Provenance of the embedded DB: the source `ch32-device-data` rev plus an fnv1a64 fingerprint
/// of the embedded generated bytes. ja: 埋め込み DB の来歴(source rev + 生成バイトの fnv1a64 指紋)。
pub fn provenance() -> DbProvenance {
    // ja: `# source: ch32-device-data@<rev> (...)` ヘッダから rev を取る(全生成物で同一)。
    let source_rev = GENERATED_SKUS
        .lines()
        .find_map(|line| line.trim_start_matches('#').trim().strip_prefix("source:"))
        .and_then(|rest| rest.split('@').nth(1))
        .map(|after_at| {
            after_at
                .split([' ', '(', '\t'])
                .next()
                .unwrap_or(after_at)
                .to_string()
        });

    // FNV-1a 64-bit over every embedded generated file, matching `flash_stub_digest`'s convention.
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for part in [
        GENERATED_SKUS,
        PROVISIONAL_SKUS,
        GENERATED_OPTION_FIELDS,
        GENERATED_DEBUG_WIRING,
        GENERATED_FLASH_GEOMETRY,
        GENERATED_FLASH_PROGRAM_METHOD,
        GENERATED_OPTION_BYTES,
        GENERATED_ESIG,
        GENERATED_USB,
        GENERATED_LINK_FIRMWARE,
        GENERATED_LINK_FIRMWARE_ISSUES,
    ] {
        for &b in part.as_bytes() {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x100_0000_01b3);
        }
    }

    DbProvenance {
        source_rev,
        digest: format!("fnv1a64:{h:016x}"),
    }
}

/// en: Flash erase/program granularities for a family (bytes; 0 = not applicable). ja: family の
/// flash 消去/書込粒度(byte、0=非該当)。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct FlashGeometry {
    /// Standard page erase (the slow PER path).
    pub page_erase: u32,
    /// Fast page erase (FTER) - the granularity `erase --range` / flash breakpoints use.
    pub fast_erase: u32,
    /// Fast program chunk.
    pub fast_program: u32,
    /// Block erase (0 when the family has none).
    pub block_erase: u32,
    /// en: The 32-bit value an erased flash word reads back as. Two groups exist across CH32:
    /// `0xFFFFFFFF` and `0xe339e339` - a property of the silicon that the reference manuals state,
    /// so a blank check has to be family-aware. None when the DB does not say.
    /// ja: 消去済み word の読み出し値(`0xFFFFFFFF` 系 / `0xe339e339` 系)。RM が書き分けている
    /// シリコン特性なので blank 判定は family 依存。DB に記述が無ければ None。
    pub erased_word: Option<u32>,
    /// en: The register bit that switches the erase sizes, as the DB writes it
    /// (`FLASH_CFGR0.DBMODE[28]`), and the sizes while it is set; None / 0 when the family's
    /// erase sizes do not depend on a mode (every family but CH32H417).
    /// ja: 消去単位を切り替えるレジスタのビットと、立っているときの大きさ。
    pub mode_bit: Option<&'static str>,
    pub page_erase_dual: u32,
    pub block_erase_dual: u32,
}

/// en: The flash geometry for a DB `family` string (e.g. `CH32L103`, `CH32V307`). None when the
/// family is not in the DB. ja: DB family の flash geometry。DB に無ければ None。
pub fn flash_geometry(family: &str) -> Option<FlashGeometry> {
    GENERATED_FLASH_GEOMETRY.lines().find_map(|line| {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            return None;
        }
        // family,page_erase,fast_erase,fast_program,block_erase,erased_word,mode_bit,
        // page_erase_dual,block_erase_dual
        let f: Vec<&str> = line.split(',').collect();
        let [
            fam,
            page,
            fast_e,
            fast_p,
            block,
            erased,
            mode,
            page_dual,
            block_dual,
        ] = f.as_slice()
        else {
            return None;
        };
        if !fam.eq_ignore_ascii_case(family) {
            return None;
        }
        Some(FlashGeometry {
            page_erase: page.parse().unwrap_or(0),
            fast_erase: fast_e.parse().unwrap_or(0),
            fast_program: fast_p.parse().unwrap_or(0),
            block_erase: block.parse().unwrap_or(0),
            erased_word: parse_generated_hex(erased),
            mode_bit: (!mode.is_empty()).then_some(*mode),
            page_erase_dual: page_dual.parse().unwrap_or(0),
            block_erase_dual: block_dual.parse().unwrap_or(0),
        })
    })
}

/// en: How a family's FLASH controller programs a page, as the reference manuals and WCH's own
/// drivers describe it (`ch32-device-data` `evidence/flash_program_method.csv`).
/// ja: family の FLASH controller の書込方式(RM と WCH driver 由来)。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FlashProgramMethod {
    /// `buffered` (FTPG + BUFRST/BUFLOAD, then STRT), `direct` (FTPG, then PG_STRT), or empty when
    /// the sources disagree and the DB did not classify the family.
    pub mode: String,
    /// The bit that starts the programming operation (`STRT` / `PG_STRT`).
    pub commit: String,
    /// en: Width of one buffer load, in bits (32 / 64 / 128). A host driving the controller word by
    /// word over DMI can only use the buffered path when this is 32. None for `direct` families.
    /// ja: buffer load 1 回の幅。DMI の word 書きで buffered を使えるのは 32 のときだけ。
    pub buffer_load_bits: Option<u32>,
    /// The data repo's confidence for the row (`confirmed` / `conflict` / ...).
    pub confidence: String,
}

/// en: The FLASH-controller programming method for a DB `family` string. None when the family is
/// not in the DB. ja: DB family の FLASH controller 書込方式。DB に無ければ None。
pub fn flash_program_method(family: &str) -> Option<FlashProgramMethod> {
    GENERATED_FLASH_PROGRAM_METHOD.lines().find_map(|line| {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') {
            return None;
        }
        // family,mode,commit,buffer_load_bits,confidence
        let f: Vec<&str> = line.split(',').collect();
        let [fam, mode, commit, bits, confidence] = f.as_slice() else {
            return None;
        };
        if !fam.eq_ignore_ascii_case(family) {
            return None;
        }
        Some(FlashProgramMethod {
            mode: (*mode).to_owned(),
            commit: (*commit).to_owned(),
            buffer_load_bits: bits.parse().ok(),
            confidence: (*confidence).to_owned(),
        })
    })
}

