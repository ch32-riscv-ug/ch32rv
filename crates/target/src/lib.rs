/// A generated hex cell (`0x...`); empty when the DB does not state the value.
fn parse_generated_hex(cell: &str) -> Option<u32> {
    let cell = cell.trim();
    let hex = cell
        .strip_prefix("0x")
        .or_else(|| cell.strip_prefix("0X"))?;
    u32::from_str_radix(hex, 16).ok()
}

